function LX(key, ...)
    local text = (ToolLocales[TOB.Locale] or ToolLocales.en)[key] or ToolLocales.en[key]
    if text == nil then return L(key, ...) end
    if select("#", ...) > 0 then return text:format(...) end
    return text
end

-- 75 -> "1 min 15 s" (in the server's language)
function FormatDuration(seconds)
    seconds = math.max(0, math.floor(seconds + 0.5))
    local m, s = seconds // 60, seconds % 60
    if m > 0 and s > 0 then return LX("time_min_sec", m, s) end
    if m > 0 then return LX("time_min", m) end
    return LX("time_sec", s)
end
