-- Returns the text for key in the language set by TOB.Locale, falling back to English
function L(key, ...)
    local text = (Locales[TOB.Locale] or Locales.en)[key] or Locales.en[key] or key
    if select("#", ...) > 0 then
        return text:format(...)
    end
    return text
end
